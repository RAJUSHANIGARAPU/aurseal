"""GenerationAgent: generate pytest files from PostmanRequest objects."""

from __future__ import annotations

import json
import logging
import re
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from api.agents.ingestion import PostmanRequest
    from api.engine.context_memory import ContextMemory
    from api.llm.base import BaseLLMClient

logger = logging.getLogger(__name__)

_SAFE_NAME = re.compile(r"[^a-zA-Z0-9_]")


def _slugify(text: str) -> str:
    return _SAFE_NAME.sub("_", text).lower().strip("_")


def _folder_key(req: PostmanRequest) -> str:
    return "_".join(req.folder_path) if req.folder_path else "default"


def _module_name_for_folder(folder_key: str) -> str:
    return f"test_{_slugify(folder_key)}.py"


def generated_module_name(req: PostmanRequest) -> str:
    """File name this request's test is written into, e.g. ``test_users.py``."""
    return _module_name_for_folder(_folder_key(req))


def generated_function_name(req: PostmanRequest) -> str:
    """Function name generated for this request, e.g. ``test_get_user_by_id``."""
    return f"test_{_slugify(req.name)}"


def generated_nodeid_suffix(req: PostmanRequest) -> str:
    """The ``file.py::function`` a pytest nodeid for this request will end with.

    This is the only reliable link between a Postman item and the test it turns
    into: the item name and the folder path are both slugified on the way in, so
    neither survives in a form a nodeid can be compared against. The full nodeid
    is out of reach here because the directory comes from ``output_dir``, which
    the caller chooses.

    Anything matching a nodeid to a request has to go through this, so the two
    cannot drift apart — the memory layer had its own idea of the naming and
    silently matched nothing for as long as it existed.
    """
    return f"{generated_module_name(req)}::{generated_function_name(req)}"


def _group_by_folder(requests: list[PostmanRequest]) -> dict[str, list[PostmanRequest]]:
    groups: dict[str, list[PostmanRequest]] = {}
    for req in requests:
        groups.setdefault(_folder_key(req), []).append(req)
    return groups


def _indent(text: str, spaces: int = 4) -> str:
    """Indent every line of text by the given number of spaces."""
    prefix = " " * spaces
    return "\n".join(prefix + line if line.strip() else line for line in text.splitlines())


class GenerationAgent:
    """Generates pytest files from ingested PostmanRequest objects.

    Template-based generation works without an API key.
    LLM-enhanced generation produces richer assertions when a key is available.
    """

    def __init__(
        self,
        output_dir: str | Path = "generated_tests",
        llm: BaseLLMClient | None = None,
        memory: ContextMemory | None = None,
    ) -> None:
        self._output_dir = Path(output_dir)
        self._llm = llm
        self._memory = memory

    def generate(self, requests: list[PostmanRequest]) -> list[Path]:
        """Generate one pytest file per folder group.

        Returns list of generated file paths.
        """
        self._output_dir.mkdir(parents=True, exist_ok=True)
        groups = _group_by_folder(requests)
        generated: list[Path] = []

        for folder_name, folder_requests in groups.items():
            file_path = self._output_dir / _module_name_for_folder(folder_name)
            content = self._render_module(folder_name, folder_requests)
            file_path.write_text(content, encoding="utf-8")
            logger.info("Generated: %s (%d tests)", file_path, len(folder_requests))
            generated.append(file_path)

        return generated

    def _render_module(self, folder_name: str, requests: list[PostmanRequest]) -> str:
        lines: list[str] = [
            f'"""Auto-generated API tests for folder: {folder_name}.',
            "",
            "Generated by GenerationAgent. Do not edit by hand.",
            '"""',
            "import requests as http_requests",
            "",
            "from api.engine.validation import ValidationEngine, ValidationRules, measure_request",
            "",
            "",
        ]

        test_blocks: list[str] = []
        for req in requests:
            test_blocks.append(self._render_test(req))

        return "\n".join(lines) + "\n\n".join(test_blocks) + "\n"

    def _render_test(self, req: PostmanRequest) -> str:
        fn_name = generated_function_name(req)
        method = req.method

        # Strip query string from URL if params will be passed separately,
        # to avoid duplicating query parameters.
        url = req.url.split("?")[0] if req.query_params and "?" in req.url else req.url

        headers_repr = json.dumps(req.headers) if req.headers else "{}"
        params_repr = json.dumps(req.query_params) if req.query_params else "{}"

        lines: list[str] = [
            f"def {fn_name}():",
            f'    """Test: {req.name} | {method} {req.url}"""',
            "    engine = ValidationEngine()",
            f"    headers = {headers_repr}",
            f"    params = {params_repr}",
        ]

        call_kwargs = ""
        if req.body and req.body_mode in ("raw_json", "raw"):
            try:
                body_str = json.dumps(req.body)
            except (TypeError, ValueError):
                body_str = repr(req.body)
            lines.append(f"    body = {body_str}")
            call_kwargs = ", json=body"

        if req.query_params:
            call_kwargs += ", params=params"

        lines += [
            "    response, duration_ms = measure_request(",
            f'        "{method}",',
            f'        "{url}",',
            "        headers=headers,",
            "        timeout=30,",
            "    )",
            "    rules = ValidationRules(",
            "        expected_status=200,",
            "        max_response_time_ms=5000,",
            "    )",
            "    result = engine.validate(response, rules, duration_ms=duration_ms)",
            '    assert result.passed, f"Validation failed: {result.failures}"',
        ]

        llm_extra = ""
        if self._llm:
            llm_extra = self._llm_assertions(req)
        if llm_extra:
            lines.append(llm_extra)

        return "\n".join(lines) + "\n"

    def _llm_assertions(self, req: PostmanRequest) -> str:
        if not self._llm:
            return ""
        prompt = (
            f"Generate 2-3 additional Python assert statements for this HTTP test:\n"
            f"Method: {req.method}\n"
            f"URL: {req.url}\n"
            f"Expected status: 200\n"
            f"Rules: check response time < 5s, response is valid JSON if Content-Type is JSON.\n"
            f"Return only the assert lines, no explanation, no imports."
        )
        result = self._llm.complete(prompt, max_tokens=256)
        if result and not result.startswith("Claude API error"):
            # Indent each line as part of the function body
            indented = [f"    {line}" for line in result.strip().splitlines() if line.strip()]
            return "\n".join(indented)
        return ""
