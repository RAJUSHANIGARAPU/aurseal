"""Select the environment tests a promotion can affect, by service. Opt-in.

A promotion moves some services to new versions. ``config/service_map.json`` says which
environment tests (``roots``: the browser and demo-system suites) exercise which service:

* ``services`` - every service name, with the hints ``derive`` uses (service-specific
  ``markers``, ``flows`` matched against ``journey_group``/``feature`` marker arguments,
  ``names`` regexes on the test id, ``fixtures`` and base ``classes``) and an optional
  ``fullSuite`` flag for a service everything depends on;
* ``core`` - cross-service flows selected for every change (test ids or id prefixes);
* ``manual`` - hand corrections, ``{test id: [services]}``, which replace what was derived;
* ``tests`` - GENERATED by ``derive``: ``{test id: {services, source}}``, with ``source``
  ``tag`` (a ``service(...)`` marker or a service-specific marker), ``inferred`` (flow,
  name, fixture or class rule) or ``manual``; ``excluded_by`` lists the markers that keep
  the test out of the default CI gate. A unit test fails when the committed ``tests``
  differ from ``derive``, so the generated part cannot be hand-edited or go stale.

``select`` returns the core flows, every test whose services meet the changed ones, every
test with no known service, and every collected test that has no map entry yet (a new
test is never silently dropped). An unknown service, or one flagged ``fullSuite``, selects
the full suite. Changed services come from a ``tools.promotion_diff --json`` delta (a
changed version, a one-sided pin and a service it could not compare all count as
changed; ``--delta -`` reads stdin) or a plain list.

Outputs: ``markdown``, ``runner`` (a space-separated node-id list for pytest; EMPTY MEANS
THE FULL SUITE) and ``json``. ``replay`` asks, for each tracked defect and the service it
lived in, whether that service's selection would have included a test naming it.

CI (``ci`` then ``run``): off unless ``SELECTIVE_TESTS=true``; when on but not
applicable it falls back to the full gate with one logged reason. A service list given
while the switch is off fails the job before any test runs.
Why: docs/ci-decisions.md#service-selection

Exit 0 ok, 1 ``check`` findings or a failed run, 2 bad input, 3 a selection with nothing
in it (which the runner format cannot express).
"""

from __future__ import annotations

import argparse
import ast
import json
import os
import re
import shlex
import subprocess
import sys
import tempfile
from collections import defaultdict
from collections.abc import Callable, Iterable, Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAP_FILE = ROOT / "config" / "service_map.json"
COLLECT_OUT_ENV = "SERVICE_MAP_COLLECT_OUT"
SOURCES = ("tag", "inferred", "manual")
FLOW_MARKERS = ("journey_group", "feature")
TAG_MARKER = "service"
CHANGED_STATUSES = frozenset({"changed", "one-sided", "not-compared"})
_SERVICE_RE = re.compile(r"[A-Za-z0-9._-]+")
_PLAIN_ID_RE = re.compile(r"[A-Za-z0-9_./-]+\.py(::[A-Za-z0-9_]+)+")
_PARAMS_RE = re.compile(r"\[.*\]$")


class SelectionError(ValueError):
    """Bad map, bad delta, bad service list: exit 2."""


# ---------------------------------------------------------------------------
# collection (a pytest plugin, active only when COLLECT_OUT_ENV is set)
# ---------------------------------------------------------------------------


def pytest_collection_finish(session) -> None:  # pragma: no cover - runs in a child pytest
    out = os.environ.get(COLLECT_OUT_ENV)
    if not out:
        return
    rows = []
    for item in session.items:
        cls = getattr(item, "cls", None)
        rows.append(
            {
                "nodeid": item.nodeid,
                "markers": {
                    m.name: [str(a) for a in m.args] for m in reversed(list(item.iter_markers()))
                },
                "fixtures": sorted(getattr(item, "fixturenames", ()) or ()),
                "classes": [c.__name__ for c in cls.__mro__[:-1]] if cls else [],
            }
        )
    Path(out).write_text(json.dumps(rows), encoding="utf-8")


@dataclass
class Collected:
    """What derive needs to know about one test id (parametrised cases merged)."""

    test_id: str
    markers: dict[str, list[str]] = field(default_factory=dict)
    fixtures: set[str] = field(default_factory=set)
    classes: set[str] = field(default_factory=set)


def strip_params(nodeid: str) -> str:
    """A node id without its parameters: one map entry per test function."""
    return _PARAMS_RE.sub("", nodeid)


def merge_rows(rows: Iterable[Mapping]) -> dict[str, Collected]:
    merged: dict[str, Collected] = {}
    for row in rows:
        tid = strip_params(row["nodeid"])
        entry = merged.setdefault(tid, Collected(tid))
        for name, args in row.get("markers", {}).items():
            known = entry.markers.setdefault(name, [])
            known.extend(a for a in args if a not in known)
        entry.fixtures.update(row.get("fixtures", ()))
        entry.classes.update(row.get("classes", ()))
    return merged


def collect(roots: Sequence[str], root: str | Path = ROOT) -> dict[str, Collected]:
    """Collect ``roots`` in a child pytest (so this session's state cannot leak in)."""
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "rows.json"
        command = [
            sys.executable,
            "-m",
            "pytest",
            "--collect-only",
            "-q",
            "-o",
            "addopts=",
            "-p",
            "no:cacheprovider",
            "-p",
            "gate.service_selection",
            *roots,
        ]
        env = {**os.environ, COLLECT_OUT_ENV: str(out)}
        done = subprocess.run(
            command, cwd=str(root), env=env, capture_output=True, text=True, check=False
        )
        if done.returncode != 0 or not out.exists():
            raise SelectionError(
                f"collection failed (exit {done.returncode}): {done.stdout[-1500:]}"
                f"{done.stderr[-1500:]}"
            )
        return merge_rows(json.loads(out.read_text(encoding="utf-8")))


