@dataclass
class Selection:
    changed: list[str]
    full_reasons: list[str] = field(default_factory=list)
    tests: dict[str, list[str]] = field(default_factory=lambda: defaultdict(list))
    notes: list[str] = field(default_factory=list)

    @property
    def full(self) -> bool:
        return bool(self.full_reasons)

    def runner(self) -> str:
        """Space-separated node ids. EMPTY MEANS THE FULL SUITE."""
        return "" if self.full else " ".join(sorted(self.tests))


def parse_services(raw: str | Iterable[str]) -> list[str]:
    """``"a,b c"`` or ``["a", "b"]`` -> names; anything else is bad input."""
    items = raw.replace(",", " ").split() if isinstance(raw, str) else list(raw)
    out = []
    for item in items:
        for name in item.replace(",", " ").split():
            if not _SERVICE_RE.fullmatch(name):
                raise SelectionError(f"bad service name {name!r} (allowed: [A-Za-z0-9._-])")
            out.append(name)
    return sorted(set(out))


def services_from_delta(data: Mapping) -> list[str]:
    """Changed services in a ``tools.promotion_diff --json`` delta."""
    rows = data.get("services") if isinstance(data, Mapping) else None
    if not isinstance(rows, list):
        raise SelectionError("delta: expected an object with a 'services' list")
    changed = []
    for row in rows:
        if not isinstance(row, Mapping) or "service" not in row or "status" not in row:
            raise SelectionError(f"delta: row without service/status: {row!r}")
        if row["status"] in CHANGED_STATUSES:
            changed.append(str(row["service"]))
        elif row["status"] != "unchanged":
            raise SelectionError(f"delta: unknown status {row['status']!r}")
    return parse_services(changed)


def select(
    changed: Iterable[str],
    smap: ServiceMap,
    current: Iterable[str] | None = None,
    *,
    allow_empty: bool = False,
) -> Selection:
    """core | tests meeting the changed services | tests with no service | unmapped tests.

    ``current`` is the collected test ids (to catch tests the map has not seen yet and to
    drop entries for deleted tests); ``None`` trusts the map.
    """
    changed = sorted(set(changed))
    selection = Selection(changed)
    if not changed and not allow_empty:
        selection.full_reasons.append("no changed services (pass --allow-empty to run core only)")
    for name in changed:
        service = smap.services.get(name)
        if service is None:
            selection.full_reasons.append(f"service {name} is not in the map")
        elif service.full_suite:
            selection.full_reasons.append(f"service {name} is flagged fullSuite")
    if selection.full:
        return selection

    current_ids = set(smap.tests) if current is None else set(current)
    stale = sorted(set(smap.tests) - current_ids)
    if stale:
        selection.notes.append(f"{len(stale)} map entr(ies) name no collected test; skipped")
    wanted = set(changed)
    for tid in sorted(current_ids):
        entry = smap.tests.get(tid)
        if smap.is_core(tid):
            selection.tests[tid].append("core flow")
        if entry is None:
            selection.tests[tid].append("no map entry yet (new test)")
            continue
        hit = sorted(wanted & set(entry["services"]))
        if hit:
            selection.tests[tid].append(f"{', '.join(hit)} ({entry['source']})")
        elif not entry["services"]:
            selection.tests[tid].append("no known service")
    return selection


def is_plain(expression: str) -> bool:
    return all(_PLAIN_ID_RE.fullmatch(token) for token in expression.split())


