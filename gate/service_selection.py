def _gate_excluded() -> list[str]:
    from gate.lanes import excluded_markers

    return excluded_markers({})


def derive_entry(collected: Collected, smap: ServiceMap, excluded: Sequence[str]) -> dict:
    """One generated map entry: manual beats tag beats inferred."""
    if collected.test_id in smap.manual:
        services, source = set(smap.manual[collected.test_id]), "manual"
    else:
        tagged = set(collected.markers.get(TAG_MARKER, ()))
        for s in smap.services.values():
            if any(m in collected.markers for m in s.markers):
                tagged.add(s.name)
        if tagged:
            services, source = tagged, "tag"
        else:
            flows = {a for m in FLOW_MARKERS for a in collected.markers.get(m, ())}
            services = {
                s.name
                for s in smap.services.values()
                if flows & set(s.flows)
                or any(re.search(p, collected.test_id) for p in s.names)
                or collected.fixtures & set(s.fixtures)
                or collected.classes & set(s.classes)
            }
            source = "inferred"
    entry: dict = {"services": sorted(services), "source": source}
    out_of_gate = sorted(m for m in excluded if m in collected.markers)
    if out_of_gate:
        entry["excluded_by"] = out_of_gate
    return entry


def derive(
    smap: ServiceMap, collected: Mapping[str, Collected], excluded: Sequence[str] | None = None
) -> dict[str, dict]:
    excluded = _gate_excluded() if excluded is None else excluded
    return {tid: derive_entry(collected[tid], smap, excluded) for tid in sorted(collected)}


def check(smap: ServiceMap, collected: Mapping[str, Collected]) -> list[str]:
    """Dead references and drift between the committed tests and derive's output."""
    problems = []
    names = set(smap.services)
    for tid, services in smap.manual.items():
        if tid not in collected:
            problems.append(f"manual entry {tid} names no collected test")
        for s in set(services) - names:
            problems.append(f"manual entry {tid}: unknown service {s!r}")
    for entry in smap.core:
        if not any(t == entry or t.startswith(entry) for t in collected):
            problems.append(f"core entry {entry} matches no collected test")
    for s in smap.services.values():
        for pattern in s.names:
            try:
                re.compile(pattern)
            except re.error as exc:
                problems.append(f"service {s.name}: bad name pattern {pattern!r} ({exc})")
    if not problems:
        derived = derive(smap, collected)
        if derived != smap.tests:
            changed = sorted(
                t for t in set(derived) | set(smap.tests) if derived.get(t) != smap.tests.get(t)
            )
            problems.append(
                f"the generated tests differ from derive for {len(changed)} test(s), "
                f"e.g. {changed[:3]}; run python -m gate.service_selection derive --write"
            )
    return problems


