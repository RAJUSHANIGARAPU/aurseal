def _changed_from_args(args: argparse.Namespace) -> list[str]:
    changed: list[str] = []
    if args.services:
        changed += parse_services(args.services)
    if args.delta:
        text = sys.stdin.read() if args.delta == "-" else Path(args.delta).read_text("utf-8")
        try:
            changed += services_from_delta(json.loads(text))
        except json.JSONDecodeError as exc:
            raise SelectionError(f"delta is not JSON: {exc}") from exc
    return sorted(set(changed))


def _append(path: str | None, text: str) -> None:
    if path:
        with open(path, "a", encoding="utf-8") as handle:
            handle.write(text + "\n")


def main(argv: Sequence[str] | None = None, env: Mapping[str, str] | None = None) -> int:
    env = os.environ if env is None else env
    parser = argparse.ArgumentParser(prog="python -m gate.service_selection")
    parser.add_argument("--map", default=str(MAP_FILE))
    sub = parser.add_subparsers(dest="command", required=True)
    der = sub.add_parser("derive", help="regenerate the per-test service map")
    der.add_argument("--write", action="store_true", help="update the map file in place")
    sub.add_parser("check", help="dead references and drift against derive")
    sel = sub.add_parser("select", help="tests for the changed services")
    sel.add_argument("--services", nargs="*", help="changed services (space or comma list)")
    sel.add_argument("--delta", help="promotion_diff --json output; - reads stdin")
    sel.add_argument("--format", choices=("markdown", "runner", "json"), default="markdown")
    sel.add_argument("--allow-empty", action="store_true", help="no change selects core only")
    sel.add_argument("--no-collect", action="store_true", help="trust the map's test list")
    rep = sub.add_parser("replay", help="would each defect's service selection name it?")
    rep.add_argument("--defects", required=True, help='JSON: {"defects": [{id, service}]}')
    rep.add_argument("--out", help="write the report here (default stdout)")
    sub.add_parser("ci", help="decide the gate step: selective=true|false")
    sub.add_parser("run", help="run the gate step on SERVICE_SELECTION")
    args = parser.parse_args(argv)

    try:
        if args.command == "ci":
            decision = ci_decide(env, lambda: ServiceMap.load(args.map))
            for reason in decision.reasons:
                print(f"service selection: full suite: {reason}")
            if decision.selective:
                print(f"service selection: {len(decision.expression.split())} test(s)")
            _append(env.get("GITHUB_OUTPUT"), f"selective={str(decision.selective).lower()}")
            _append(env.get("GITHUB_OUTPUT"), f"expression={decision.expression}")
            return 0
        if args.command == "run":
            ids = (env.get("SERVICE_SELECTION") or "").split()
            if not ids or not is_plain(" ".join(ids)):
                print("service selection: no plain selection to run", file=sys.stderr)
                return 2
            command = gate_command(ids)
            print(shlex.join([*command[:1], f"<{len(ids)} node ids>", *command[1 + len(ids) :]]))
            return subprocess.run(
                [sys.executable, "-m", *command], cwd=str(ROOT), check=False
            ).returncode

        smap = ServiceMap.load(args.map)
        if args.command == "derive":
            smap.tests = derive(smap, collect(smap.roots))
            text = smap.dumps()
            if args.write:
                Path(args.map).write_text(text, encoding="utf-8")
                print(f"wrote {len(smap.tests)} test(s) to {args.map}")
            else:
                sys.stdout.write(text)
            return 0
        if args.command == "check":
            problems = check(smap, collect(smap.roots))
            for problem in problems:
                print(problem)
            print(f"{len(problems)} problem(s) in {args.map}")
            return 1 if problems else 0
        if args.command == "replay":
            data = json.loads(Path(args.defects).read_text(encoding="utf-8"))
            defects = data.get("defects") if isinstance(data, Mapping) else None
            if not isinstance(defects, list):
                raise SelectionError("defects file: expected an object with a 'defects' list")
            report = replay(defects, smap)
            if args.out:
                Path(args.out).write_text(report, encoding="utf-8")
                print(f"wrote {args.out}")
            else:
                sys.stdout.write(report)
            return 0

        changed = _changed_from_args(args)
        current = None if args.no_collect else collect(smap.roots).keys()
        selection = select(changed, smap, current, allow_empty=args.allow_empty)
    except (SelectionError, OSError, json.JSONDecodeError) as exc:
        print(f"service selection: {exc}", file=sys.stderr)
        return 2

    if not selection.full and not selection.tests:
        print("service selection: nothing selected", file=sys.stderr)
        return 3
    if args.format == "runner":
        print(selection.runner())
    elif args.format == "json":
        print(render_json(selection, smap))
    else:
        sys.stdout.write(render_markdown(selection, smap))
    return 0


if __name__ == "__main__":
    sys.exit(main())
