REPLAY_LIMITS = (
    "A test *naming* a defect is a mention, not proof that it asserts the defect's behaviour.",
    "The service a defect lived in comes from the input file; a wrong attribution is a wrong "
    "verdict.",
    "The selection is replayed against today's map and tests, not the ones at the time.",
    "Parametrised cases count once; test sizes are test functions, not executions.",
)


def naming_tests(
    defect_ids: Iterable[str], smap: ServiceMap, root: str | Path = ROOT
) -> dict[str, set[str]]:
    """``{defect id: test ids}``: functions mentioning it, or every test of a module that does."""
    ids = list(defect_ids)
    found: dict[str, set[str]] = {d: set() for d in ids}
    by_file: dict[str, list[str]] = defaultdict(list)
    for tid in smap.tests:
        by_file[tid.split("::", 1)[0]].append(tid)
    for rel, tids in by_file.items():
        path = Path(root) / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        if not any(d in text for d in ids):
            continue
        functions: dict[str, str] = {}
        for node in ast.walk(ast.parse(text)):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                start = min([d.lineno for d in node.decorator_list] + [node.lineno])
                functions[node.name] = "\n".join(text.splitlines()[start - 1 : node.end_lineno])
        for defect in ids:
            pattern = re.compile(rf"(?<![A-Za-z0-9-]){re.escape(defect)}(?![0-9])")
            if not pattern.search(text):
                continue
            direct = {t for t in tids if pattern.search(functions.get(t.rsplit("::", 1)[-1], ""))}
            found[defect] |= direct or set(tids)
    return found


def replay(defects: Sequence[Mapping], smap: ServiceMap, root: str | Path = ROOT) -> str:
    rows = []
    for defect in defects:
        if "id" not in defect or "service" not in defect:
            raise SelectionError(f"defect without id/service: {defect!r}")
    named = naming_tests([str(d["id"]) for d in defects], smap, root)
    gate_size = sum(1 for e in smap.tests.values() if not e.get("excluded_by"))
    per_service: dict[str, Selection] = {}
    for defect in defects:
        did, service = str(defect["id"]), str(defect["service"])
        selection = per_service.setdefault(service, select([service], smap))
        tests = named[did]
        if not tests:
            verdict = "NO-ENV-TEST"
        else:
            hit = tests if selection.full else tests & set(selection.tests)
            in_gate = {t for t in hit if not smap.tests.get(t, {}).get("excluded_by")}
            verdict = "SELECTED" if in_gate else "SELECTED-NOT-IN-GATE" if hit else "MISSED"
        rows.append((did, service, verdict, sorted(tests)))

    counts = defaultdict(int)
    for _, _, verdict, _ in rows:
        counts[verdict] += 1
    lines = [
        "# Selection replay",
        "",
        "Would the selection for the service a defect lived in have run a test that names it?",
        "",
        "Verdicts: "
        + ", ".join(
            f"{v} {counts[v]}"
            for v in ("SELECTED", "SELECTED-NOT-IN-GATE", "MISSED", "NO-ENV-TEST")
        ),
        "",
        "| Defect | Service | Verdict | Tests naming it |",
        "|---|---|---|---|",
    ]
    for did, service, verdict, tests in rows:
        shown = ", ".join(f"`{t}`" for t in tests[:3]) + (" ..." if len(tests) > 3 else "")
        lines.append(f"| {did} | {service} | {verdict} | {shown or '-'} |")
    lines += [
        "",
        "## Selection size per service",
        "",
        "| Service | Selected | In the default gate | Full gate | Share |",
        "|---|---|---|---|---|",
    ]
    for service, selection in sorted(per_service.items()):
        if selection.full:
            lines.append(f"| {service} | full suite | {gate_size} | {gate_size} | 100% |")
            continue
        chosen = set(selection.tests)
        in_gate = sum(1 for t in chosen if not smap.tests.get(t, {}).get("excluded_by"))
        share = f"{in_gate / gate_size:.0%}" if gate_size else "-"
        lines.append(f"| {service} | {len(chosen)} | {in_gate} | {gate_size} | {share} |")
    lines += ["", "## Limits", ""] + [f"- {limit}" for limit in REPLAY_LIMITS]
    return "\n".join(lines) + "\n"


