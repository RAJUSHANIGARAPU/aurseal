def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render_markdown(selection: Selection, smap: ServiceMap) -> str:
    lines = [f"# Service selection: {', '.join(selection.changed) or '(none)'}", ""]
    if selection.full:
        lines += ["**Full suite.**", ""] + [f"- {r}" for r in selection.full_reasons]
        return "\n".join(lines) + "\n"
    in_gate = [t for t in selection.tests if not smap.tests.get(t, {}).get("excluded_by")]
    lines += [
        f"{len(selection.tests)} of {len(smap.tests)} mapped test(s) selected; "
        f"{len(in_gate)} carry no marker the default CI gate excludes.",
        "",
        "| Test | Services | Source | Why | Gate |",
        "|---|---|---|---|---|",
    ]
    for tid in sorted(selection.tests):
        entry = smap.tests.get(tid, {})
        excluded = entry.get("excluded_by")
        gate = f"excluded by `{'`, `'.join(excluded)}`" if excluded else ""
        lines.append(
            f"| `{_cell(tid)}` | {', '.join(entry.get('services', [])) or '-'} | "
            f"{entry.get('source', 'unmapped')} | {_cell('; '.join(selection.tests[tid]))} "
            f"| {gate} |"
        )
    lines += [""] + [f"Note: {n}" for n in selection.notes]
    return "\n".join(lines).rstrip() + "\n"


def render_json(selection: Selection, smap: ServiceMap) -> str:
    return json.dumps(
        {
            "changed": selection.changed,
            "full": selection.full,
            "full_reasons": selection.full_reasons,
            "tests": {
                t: {
                    "why": selection.tests[t],
                    "excluded_by": smap.tests.get(t, {}).get("excluded_by", []),
                }
                for t in sorted(selection.tests)
            },
            "runner": selection.runner(),
            "notes": selection.notes,
        },
        indent=2,
    )


