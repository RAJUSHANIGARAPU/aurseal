@dataclass
class CiDecision:
    selective: bool
    expression: str = ""
    reasons: list[str] = field(default_factory=list)


def _true(value: str | None) -> bool:
    return (value or "").strip().lower() in ("true", "1", "yes")


def ci_decide(
    env: Mapping[str, str],
    smap_loader: Callable[[], ServiceMap] = ServiceMap.load,
    collector: Callable[[Sequence[str]], Iterable[str]] | None = None,
    lane: Callable[[list[str]], list[str]] | None = None,
) -> CiDecision:
    """Whether the gate step runs a selection, and if not, the one-line reason.

    Raises SelectionError when a service list is supplied while the switch is off: a
    caller who asked for a selection must not get a full run that looks like one.
    """
    raw = (env.get("CHANGED_SERVICES") or "").strip()
    if not _true(env.get("SELECTIVE_TESTS")):
        if raw:
            raise SelectionError(
                f"CHANGED_SERVICES={raw!r} was supplied but SELECTIVE_TESTS is off; "
                "switch it on or drop the list"
            )
        return CiDecision(False)

    def fallback(reason: str) -> CiDecision:
        return CiDecision(False, reasons=[reason])

    if not raw:
        return fallback("no input: no changed services supplied")
    try:
        changed = parse_services(raw)
    except SelectionError as exc:
        return fallback(f"bad input: {exc}")
    if _true(env.get("OTHER_FILTER")):
        return fallback("another filter is already set (a preset or a selection input)")
    try:
        shards = int(env.get("SHARD_COUNT") or "1")
    except ValueError:
        return fallback(f"bad input: SHARD_COUNT={env.get('SHARD_COUNT')!r}")
    if shards > 1:
        return fallback(f"sharding is on ({shards} shards)")
    try:
        smap = smap_loader()
        current = (collector or (lambda roots: collect(roots).keys()))(smap.roots)
        selection = select(changed, smap, current)
    except Exception as exc:  # any selector failure falls back, it never blocks the gate
        return fallback(f"selector error: {exc}")
    if selection.full:
        return fallback("; ".join(selection.full_reasons))
    expression = selection.runner()
    if not expression or not is_plain(expression):
        return fallback("the runner expression is not plain node ids")
    try:
        in_lane = (lane or gate_lane_ids)(expression.split())
    except Exception as exc:
        return fallback(f"selector error: {exc}")
    if not in_lane:
        return fallback("nothing selected is in the gate lane")
    return CiDecision(True, " ".join(in_lane))


def gate_command(node_ids: Sequence[str]) -> list[str]:
    """The literal gate step, narrowed to node ids (same markers and execution flags)."""
    from gate.run_inputs import default_command

    command = default_command()
    return [command[0], *node_ids, *command[1:]]


def gate_lane_ids(node_ids: Sequence[str]) -> list[str]:
    """The selected ids the gate's marker expression keeps, as pytest collects them."""
    from core.ci_selection import collect_node_ids

    command = gate_command(node_ids)
    marker = command[command.index("-m") + 1]
    return sorted(collect_node_ids([*node_ids, "-m", marker], ROOT))


