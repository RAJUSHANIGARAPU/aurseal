@dataclass(frozen=True)
class Service:
    name: str
    full_suite: bool = False
    markers: tuple[str, ...] = ()
    flows: tuple[str, ...] = ()
    names: tuple[str, ...] = ()
    fixtures: tuple[str, ...] = ()
    classes: tuple[str, ...] = ()


@dataclass
class ServiceMap:
    roots: tuple[str, ...]
    services: dict[str, Service]
    core: tuple[str, ...] = ()
    manual: dict[str, list[str]] = field(default_factory=dict)
    tests: dict[str, dict] = field(default_factory=dict)

    @classmethod
    def from_json(cls, data: Mapping) -> ServiceMap:
        if not isinstance(data, Mapping) or not isinstance(data.get("services"), Mapping):
            raise SelectionError("service map: expected an object with a 'services' object")
        services = {}
        for name, raw in data["services"].items():
            raw = raw or {}
            services[name] = Service(
                name=name,
                full_suite=bool(raw.get("fullSuite", False)),
                markers=tuple(raw.get("markers", ())),
                flows=tuple(raw.get("flows", ())),
                names=tuple(raw.get("names", ())),
                fixtures=tuple(raw.get("fixtures", ())),
                classes=tuple(raw.get("classes", ())),
            )
        return cls(
            roots=tuple(data.get("roots", ())),
            services=services,
            core=tuple(data.get("core", ())),
            manual={k: list(v) for k, v in (data.get("manual") or {}).items()},
            tests=dict(data.get("tests") or {}),
        )

    @classmethod
    def load(cls, path: str | Path = MAP_FILE) -> ServiceMap:
        try:
            return cls.from_json(json.loads(Path(path).read_text(encoding="utf-8")))
        except (OSError, json.JSONDecodeError) as exc:
            raise SelectionError(f"cannot read {path}: {exc}") from exc

    def to_json(self) -> dict:
        services = {}
        for name, s in self.services.items():
            raw: dict = {}
            if s.full_suite:
                raw["fullSuite"] = True
            for key in ("markers", "flows", "names", "fixtures", "classes"):
                if getattr(s, key):
                    raw[key] = list(getattr(s, key))
            services[name] = raw
        return {
            "roots": list(self.roots),
            "services": services,
            "core": list(self.core),
            "manual": self.manual,
            "tests": {k: self.tests[k] for k in sorted(self.tests)},
        }

    def dumps(self) -> str:
        """The map as committed: hand-written parts indented, one line per generated test."""
        data = self.to_json()
        tests = data.pop("tests")
        head = json.dumps(data, indent=2)[:-2]  # drop the closing "\n}"
        rows = [f"    {json.dumps(k)}: {json.dumps(v)}" for k, v in tests.items()]
        body = ",\n".join(rows)
        return head + ',\n  "tests": {\n' + body + ("\n  }\n}\n" if rows else "  }\n}\n")

    def is_core(self, tid: str) -> bool:
        return any(tid == c or tid.startswith(c) for c in self.core)


